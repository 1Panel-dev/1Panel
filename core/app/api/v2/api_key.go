func bindAPIKeyRequest(c *gin.Context, value interface{}) bool {
	if _, err := auth.RequireAPIKeyManagement(c); err != nil {
		helper.BadAuth(c, "ErrNotLogin", nil)
		return false
	}
	decoder := json.NewDecoder(http.MaxBytesReader(c.Writer, c.Request.Body, 32<<10))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(value); err != nil {
		helper.BadRequest(c, err)
		return false
	}
	if err := decoder.Decode(new(interface{})); err != io.EOF {
		helper.BadRequest(c, errors.New("unexpected JSON data"))
		return false
	}
	return true
}

func apiKeyError(c *gin.Context, err error) {
	var business buserr.BusinessError
	if errors.As(err, &business) {
		helper.ErrorWithDetail(c, http.StatusBadRequest, business.Msg, business.Err)
		return
	}
	helper.InternalServer(c, err)
}

// Swag's legacy || syntax combines schemes in one requirement (AND);
// separate @Security lines represent alternative authentication methods.
// @Tags API Key
// @Summary List the current account's API keys
// @Description Accepts a panel login session with CSRF protection, or a valid API Key signature. The authenticated account determines ownership; another account cannot be selected in the request.
// @Description Returns key metadata and masked hints, never plaintext secrets. The legacy key is included when present; deleted keys are excluded.
// @Description Authentication and business errors use HTTP 200 with envelope code 400, 401 or 500; check code rather than HTTP status alone.
// @Accept json
// @Produce json
// @Param request body dto.APIKeySearch true "Pagination and revoked-key filter"
// @Param 1Panel-Key-ID header string false "Optional ID of the authenticating independent key; omit for legacy keys"
// @Param 1Panel-Signature-Version header string false "Signature algorithm; omission accepts either supported algorithm" Enums(v1,md5,hmac-sha256)
// @Success 200 {object} dto.Response{data=dto.APIKeyPage} "code=200 on success; data is null on errors"
// @Failure 403 {object} dto.Response "Invalid or missing CSRF token for a session request"
// @Header 200 {string} Cache-Control "no-store"
// @Security ApiKeyAuth || Timestamp
// @Security PanelSession || CSRFToken
// @Router /core/auth/api/keys/search [post]
func (b *BaseApi) SearchAPIKeys(c *gin.Context) {
	var req dto.APIKeySearch
	if !bindAPIKeyRequest(c, &req) {
		return
	}
	result, err := service.NewAPIKeyService().Search(c, req)
	if err != nil {
		apiKeyError(c, err)
		return
	}
	c.Header("Cache-Control", "no-store")
	helper.SuccessWithData(c, result)
}

