// @Tags API Key
// @Summary Reveal an independent API key's plaintext secret
// @Description Requires a panel login session and CSRF token. API Key authentication is not supported, including requests that also contain a valid session cookie; omit all 1Panel authentication headers.
// @Description Only the current account's independent keys can be revealed. Submit the current revision returned by search. Legacy, revoked and deleted keys are rejected; disabled or expired keys can still be revealed.
// @Description Secret disclosure is audited. Authentication and business errors use HTTP 200 with envelope code 400, 401 or 500. The response must not be cached or logged.
// @Accept json
// @Produce json
// @Param request body dto.APIKeyMutation true "Independent key ID and current revision"
// @Success 200 {object} dto.Response{data=dto.APIKeyRevealed} "code=200 on success; data is null on errors"
// @Failure 403 {object} dto.Response "Invalid or missing CSRF token"
// @Header 200 {string} Cache-Control "no-store"
// @Security PanelSession || CSRFToken
// @Router /core/auth/api/keys/reveal [post]
func (b *BaseApi) RevealAPIKey(c *gin.Context) {
	c.Header("Cache-Control", "no-store")
	if _, err := auth.RequireAPIKeySession(c); err != nil {
		helper.BadAuth(c, "ErrNotLogin", nil)
		return
	}
	var req dto.APIKeyMutation
	if !bindAPIKeyRequest(c, &req) {
		return
	}
	result, err := service.NewAPIKeyService().Reveal(c, req)
	if err != nil {
		apiKeyError(c, err)
		return
	}
	helper.SuccessWithData(c, result)
}
